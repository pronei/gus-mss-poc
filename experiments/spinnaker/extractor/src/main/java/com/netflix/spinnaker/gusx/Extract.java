package com.netflix.spinnaker.gusx;

import java.io.File;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * The extraction, run inside the service's own class loader.
 *
 * <p>{@link Main} is the only thing that runs outside it; everything here
 * resolves Jackson, Spring and Retrofit against the service's jars, which is
 * what lets {@link Shape} drive the service's configured {@code ObjectMapper}
 * (D1(c), D7) rather than one of ours.
 */
public final class Extract {

  /** Invoked reflectively by {@link Main}. Returns a process exit code. */
  public static int run(String[] argv) {
    Args a = Args.parse(argv);
    if (a == null) {
      System.err.println(Args.USAGE);
      return 2;
    }
    Diag diag = new Diag();
    try {
      ClassLoader cl = Extract.class.getClassLoader();
      List<File> entries = Classpath.read(a.classpathDir, a.service);
      List<File> jars = Classpath.jars(entries);
      diag.count("classpath-entries", entries.size());
      diag.count("classpath-jars", jars.size());

      ClassIndex index = new ClassIndex(jars);
      diag.count("classes-on-classpath", index.owner.size());

      Mapper mapper = new Mapper(a.service, index, cl, diag);
      diag.count("jackson-modules-registered", mapper.modulesRegistered.size());
      for (String f : mapper.modulesFailed) {
        diag.loss("module-not-registered", f);
      }

      boolean openAccept = mapper.enumsOpenOnAccept();
      Shape shape = new Shape(mapper.mapper, diag, openAccept, false, a.presenceDeclared);

      List<Endpoint> endpoints = new ArrayList<>();
      if (!"client".equals(a.sides)) {
        List<Endpoint> provider = new ProviderScan(cl, index, shape, diag, a.service).scan();
        diag.count("provider-endpoints", provider.size());
        endpoints.addAll(provider);
      }
      if (!"provider".equals(a.sides)) {
        Mesh mesh = null;
        if (a.mesh != null && a.mesh.isFile()) {
          mesh = new Mesh(a.mesh);
        } else {
          diag.loss("mesh-missing", "no --mesh: caller endpoints cannot be bound to a provider");
        }
        if (mesh != null) {
          List<Endpoint> client =
              new CallerScan(cl, index, shape, diag, mesh, a.service, a.korkRows, a.indirectFiat)
                  .scan();
          diag.count("client-endpoints", client.size());
          endpoints.addAll(client);
        }
      }

      diag.count("components", shape.components.size());
      Map<String, Object> doc =
          Doc.build(a.service, a.version, endpoints, shape.components, diag);

      a.out.getAbsoluteFile().getParentFile().mkdirs();
      try (PrintWriter w = new PrintWriter(a.out, StandardCharsets.UTF_8)) {
        w.print(header(a, mapper, openAccept));
        w.print(Yaml.write(doc));
      }

      if (a.diag != null) {
        diag.writeJson(a.diag);
      }
      System.err.printf(
          "%s%s: %d endpoints, %d components, %d flagged, mapper: %s (%d modules)%n",
          a.service,
          a.version.isEmpty() ? "" : "@" + a.version,
          endpoints.size(),
          shape.components.size(),
          diag.flagged.size(),
          mapper.recipe,
          mapper.modulesRegistered.size());
      return 0;
    } catch (Throwable t) {
      System.err.println("extract: " + t);
      t.printStackTrace();
      return 2;
    }
  }

  private static String header(Args a, Mapper mapper, boolean openAccept) {
    StringBuilder b = new StringBuilder();
    b.append("# Generated by the GUS contract extractor (G1) - do not edit.\n");
    b.append("# service: ").append(a.service);
    if (!a.version.isEmpty()) {
      b.append("  version: ").append(a.version);
    }
    b.append('\n');
    b.append("# classpath: ").append(a.classpathDir).append('\n');
    b.append("# object mapper: ").append(mapper.recipe).append('\n');
    b.append("# jackson modules: ")
        .append(mapper.modulesRegistered.isEmpty() ? "(none)" : String.join(", ", mapper.modulesRegistered))
        .append('\n');
    b.append("# enums on the accept side: ").append(openAccept ? "open (D8)" : "closed").append('\n');
    b.append("# presence profile: ").append(a.presenceDeclared ? "declared" : "none").append('\n');
    b.append("# kork Front50Service rows: ").append(a.korkRows ? "kept" : "dropped").append('\n');
    b.append("# indirect FiatService rows: ").append(a.indirectFiat ? "kept" : "dropped").append('\n');
    return b.toString();
  }

  private Extract() {}
}
