"""results/compare.md from compare.py's summary: the tables the README quotes."""
import collections
import json
import os

from common import HERE, SERVICES

RESULTS = os.path.join(HERE, 'results')
CONJUNCTS = ('C1', 'C2', 'C3', 'C4', 'TGT')
COMPONENTS = ('params', 'headers', 'body', 'response')


def _pct(x):
    return '%.1f %%' % (100 * x)


def _table(header, rows):
    out = ['| ' + ' | '.join(header) + ' |', '|' + '|'.join('---' for _ in header) + '|']
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return out


def write(summary, results):
    lines = ['# Spinnaker projection — what the checker saw', '',
             'Generated by `compare.py` from `results/`, `graph/`, `triage/` and S4; do not edit by hand.', '']
    presences = [p for p in ('none', 'declared') if p in summary]

    lines += ['## Run', '']
    rows = []
    for p in presences:
        t = summary[p]['totals']
        times = ''
        path = os.path.join(RESULTS, p, 'run-times.txt')
        if os.path.exists(path):
            with open(path) as f:
                times = f.read().strip()
        rows.append([p, t['scenarios'], t['not_safe'], t['errors'], len(t['posthoc_fail']), t['tier3_edges'], times])
    lines += _table(['profile', 'scenarios', 'not safe as proposed', 'could not evaluate', 'post-hoc FAIL', 'Tier-3 edges', 'wall'], rows) + ['']

    lines += ['## Legs at the two ends of the range (every matched edge, both declarations at that BOM)', '']
    rows = []
    for p in presences:
        for bom, s in sorted(summary[p]['static_legs'].items()):
            rows.append([p, bom, s['edges'], _pct(s['wrapper_reading']['untyped_edge_share']),
                         _pct(s['wrapper_reading']['live_leg_share']), _pct(s['wrapper_reading']['vacuous_leg_share']),
                         _pct(s['body_reading']['untyped_edge_share']), _pct(s['body_reading']['live_leg_share']),
                         _pct(s['body_reading']['vacuous_leg_share']),
                         ', '.join('%s %s' % (k, _pct(v)) for k, v in s['component_live_share'].items())])
    lines += _table(['profile', 'BOM', 'edges', 'untyped edges', 'live legs', 'vacuous legs',
                     'untyped edges (body reading)', 'live legs (body reading)', 'vacuous legs (body reading)',
                     'live share per component'], rows)
    lines += ['', 'Review pass 2 at 1.38.0 on the scout tables (body reading, S1+S2): untyped edges 0.8 %, live legs 24.7 %, vacuous legs 18.9 %.', '']

    for p in presences:
        lines += ['## Pairs (%s profile)' % p, '']
        rows = []
        for pair, r in sorted(summary[p]['pairs'].items()):
            labels = sorted({l['claim'].replace('CLAIM-', '') + ' ' + l['kind'] for l in summary['labels'] if l['pair'] == pair})
            live = r['live_share_at_to']
            vac = r['vacuous_share_at_to']
            rows.append([pair, '%s → %s' % (r['from'], r['to']), len(r['changed']), r['edges_in_graph'], r['gate_excluded'],
                         '+%d/−%d' % (r['added'], r['removed']),
                         'p %.0f/%.0f b %.0f/%.0f r %.0f/%.0f' % (100 * live['params'], 100 * vac['params'], 100 * live['body'],
                                                                  100 * vac['body'], 100 * live['response'], 100 * vac['response']),
                         r['all_decision'], '%d/%d' % (len(r['not_safe']), r['batches']),
                         len(r['posthoc_fail']), r['findings'], '%d (%d edges)' % (r['evidence'], len(r['evidence_edges'])),
                         ' '.join('%s %d' % (c, r['evidence_by_conjunct'].get(c, 0)) for c in CONJUNCTS if r['evidence_by_conjunct'].get(c)),
                         '; '.join(labels)])
        lines += _table(['pair', 'BOMs', 'pins changed', 'edges', 'gate-excluded', 'edges +/−',
                         'live/vacuous % at θ\' (params, body, response)', '`all`', 'not safe',
                         'post-hoc FAIL', 'breaks (`all`)', 'on live legs', 'live by conjunct', 'S4 labels'], rows) + ['']

        t = summary[p]['totals']
        lines += ['### Breaks over all pairs (%s profile)' % p, '']
        lines += _table(['', 'all breaks', 'on live legs'],
                        [[c, t['by_conjunct']['all'].get(c, 0), t['by_conjunct']['evidence'].get(c, 0)] for c in CONJUNCTS]
                        + [[c, t['by_component']['all'].get(c, 0), t['by_component']['evidence'].get(c, 0)] for c in COMPONENTS]) + ['']
        lines += _table(['rule', 'all breaks', 'on live legs'],
                        [[k, v, t['by_rule']['evidence'].get(k, 0)] for k, v in sorted(t['by_rule']['all'].items(), key=lambda kv: -kv[1])]) + ['']
        lines += ['Breaks by the state of their leg at the conjunct\'s pairing: ' +
                  ', '.join('%s %d' % kv for kv in sorted(t['by_state'].items(), key=lambda kv: -kv[1])) +
                  '; on collided edges: %d.' % t['collided_findings'], '']
        if t['posthoc_fail']:
            lines += ['Post-hoc certificate FAIL: ' + ', '.join('%s-%s' % x for x in t['posthoc_fail']), '']
        else:
            lines += ['Post-hoc certificate FAIL: none.', '']
        errs = [(pair, b, e) for pair, r in sorted(summary[p]['pairs'].items()) for b, e in sorted(r['errors'].items())]
        if errs:
            lines += ['Could not evaluate (exit 2):', '']
            lines += ['* %s-%s: `%s`' % (pair, b, e.splitlines()[-1][:300] if e else '') for pair, b, e in errs] + ['']

        drift = results[p]['drift']
        lines += ['### Caller drift (%s profile)' % p, '',
                  'Edges of a pair graph whose caller declaration differs between the two BOMs; `changed` names the components.', '']
        rows = [[d['pair'], d['edge'], '%s %s' % (d['verb'], d['path']), d['caller_pin'], d['changed'], d['opacity'],
                 d['states_to'], d['caller_conjunct_breaks'] or '—', d['evidence_breaks']] for d in drift]
        lines += _table(['pair', 'edge', 'endpoint', 'caller pin', 'changed', 'opacity', 'legs at θ\'', 'C2/C4/TGT breaks', 'on live legs'], rows) + ['']

    if 'profiles' in summary:
        pr = summary['profiles']
        lines += ['## The two presence profiles', '',
                  'Breaks in both profiles: %d. Only under `declared`: %d. Only under `none`: %d. '
                  'Batches whose verdict or safe subset differs: %d.' % (
                      pr['breaks_in_both'], len(pr['breaks_only_in']['declared']), len(pr['breaks_only_in']['none']),
                      len(pr['batches_with_different_verdict_or_subset'])), '']
        rows = [[p, x['pair'], x['edge'], x['conjunct'], x['violation_path'], x['rule'], x['state'], x['evidence']]
                for p in ('declared', 'none') for x in pr['breaks_only_in'][p]]
        if rows:
            lines += _table(['only in', 'pair', 'edge', 'conjunct', 'path', 'rule', 'leg state', 'live'], rows) + ['']
        rows = [[v['pair'], v['batch'], v['none'], v['declared']] for v in pr['batches_with_different_verdict_or_subset']]
        if rows:
            lines += _table(['pair', 'batch', 'none (verdict, safe subset)', 'declared (verdict, safe subset)'], rows) + ['']

    lines += ['## S4 labels against the checker', '']
    rows = []
    for l in summary['labels']:
        cells = [l['claim'].replace('CLAIM-', ''), l['kind'], l['label_pair'], l['pair'], l['mapping']]
        for p in presences:
            x = l.get(p, {})
            cells.append('%s; not safe %s/46; named edges: %d breaks, %d live' % (
                x.get('all'), x.get('batches_not_safe'), x.get('findings_on_named_edges', 0), x.get('evidence_on_named_edges', 0)))
        rows.append(cells)
    lines += _table(['claim', 'kind', 'label', 'pair', 'mapping'] + ['checker (%s)' % p for p in presences], rows) + ['']
    for l in summary['labels']:
        if 'trace' not in l:
            continue
        lines += ['### %s at %s' % (l['claim'], l['pair']), '', '> %s' % l['quote'], '']
        for t in l['trace']:
            lines += ['```', json.dumps(t, indent=1, sort_keys=True, default=str), '```', '']
    with open(os.path.join(RESULTS, 'compare.md'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
